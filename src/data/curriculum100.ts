export const CURRICULUM_100: SquareMetadata[] = RAW_CURRICULUM.map(item => {
  const snake = SNAKE_MAP.get(item.id);
  const ladder = LADDER_MAP.get(item.id);

  let type: SquareMetadata['type'] = 'normal';
  let snakeOrLadderId: string | undefined = undefined;

  if (item.id === 1) {
    type = 'start';
  } else if (item.id === 100) {
    type = 'finish';
  } else if (ladder) {
    type = 'ladder_start';
    snakeOrLadderId = ladder.id;
  } else if (snake) {
    type = 'snake_head';
    snakeOrLadderId = snake.id;
  } else if (item.isCheckpoint) {
    type = 'checkpoint';
  }

  return {
    ...item,
    type,
    snakeOrLadderId: snakeOrLadderId ?? undefined
  };
});

